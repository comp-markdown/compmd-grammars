// Writes `src/syntax.ts` from the syntax every grammar shares (`../syntax/`): each token's Lezer tag (`tokens.json`)
// and the syntax's pieces (`patterns.js`). The package is published on its own, so it carries a copy, committed as
// tree-sitter's generated parsers are; `--check` fails when the copy is out of date.
//
//   node generate.js            write it
//   node generate.js --check    check it

import fs from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const syntax = path.join(here, "..", "syntax");
const target = path.join(here, "src", "syntax.ts");

const { tokens } = JSON.parse(fs.readFileSync(path.join(syntax, "tokens.json"), "utf8"));
const patterns = createRequire(import.meta.url)(path.join(syntax, "patterns.js"));

const tags = Object.fromEntries(Object.entries(tokens).map(([name, token]) => [name, token.lezer]));

const text = `// Generated by \`node generate.js\` from compmd-grammars' \`syntax/\`: edit \`syntax/tokens.json\` or \`syntax/patterns.js\`,
// then generate again.

/** Each token's Lezer highlighting tag, by the token's name (\`syntax/tokens.json\`). */
export const TOKEN_TAGS = ${JSON.stringify(tags, null, 2)} as const;

/** A token's name. */
export type Token = keyof typeof TOKEN_TAGS;

/** The syntax's pieces as regular-expression sources (\`syntax/patterns.js\`). */
export const PATTERNS = ${JSON.stringify(patterns, null, 2)} as const;
`;

if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== text) {
    console.error("src/syntax.ts is out of date: run `node generate.js`");
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(target, text);
}
